/**
 * Le panneau des choix de la bande-annonce : sous-titres et qualité, les
 * modèles d'options de shared (`trailerSubtitleOptions`, `trailerQualityOptions`)
 * — « Désactivés » puis les pistes du relais, « Auto » puis les HAUTEURS.
 * L'apparence du panneau des pistes du lecteur (`TrackSelector`) : détaché, à
 * fond quasi opaque, il suit le thème — et donc pas de `backdrop-filter`.
 */

import { memo, type ReactNode } from "react";
import { useTranslation } from "react-i18next";
import { motion } from "framer-motion";
import {
  TRAILER_QUALITY_AUTO, TRAILER_SUBTITLES_OFF, languageName, trailerQualityOptions, trailerSubtitleOptions,
  type TrailerStream,
} from "@tentacle-tv/shared";

interface Props {
  stream: TrailerStream;
  subtitle: string | null;
  quality: number | null;
  onSubtitle: (lang: string | null) => void;
  onQuality: (height: number | null) => void;
  onClose: () => void;
}

export const TrailerSettingsPanel = memo(function TrailerSettingsPanel({ stream, subtitle, quality, onSubtitle, onQuality, onClose }: Props) {
  const { t, i18n } = useTranslation("common");
  const locale = (i18n.language ?? "en").slice(0, 2);
  const heights = stream.qualities.map((q) => q.height);
  const subtitleOptions = stream.subtitles.length > 0 ? trailerSubtitleOptions(stream.subtitles.map((s) => ({ id: s.lang })), subtitle) : [];
  const qualityOptions = heights.length >= 2 ? trailerQualityOptions(heights, quality) : [];

  return (
    <motion.div data-panneau-detache
      initial={{ opacity: 0, y: 10 }}
      animate={{ opacity: 1, y: 0 }}
      exit={{ opacity: 0, y: 10 }}
      className="absolute bottom-20 right-6 z-50 w-72 rounded-xl border border-line-subtle bg-[var(--surface-dropdown)] p-4"
      onClick={(e) => e.stopPropagation()}
    >
      <div className="mb-3 flex items-center justify-between">
        <span className="text-sm font-semibold text-content-primary">{t("player:settings")}</span>
        <button onClick={onClose} className="text-content-quaternary hover:text-content-primary" aria-label={t("player:close")}>&times;</button>
      </div>
      <div className="max-h-[min(60vh,22rem)] overflow-y-auto scrollbar-thin">
        {subtitleOptions.length > 0 && (
          <Section title={t("common:trailerSubtitles")}>
            {subtitleOptions.map((option) => {
              const track = stream.subtitles.find((s) => s.lang === option.key);
              const named = track ? languageName(track.lang, locale) : "";
              // Sans nom de langue connu du moteur JS (le code en capitales), celui du serveur.
              const label = option.key === TRAILER_SUBTITLES_OFF
                ? t("common:trailerSubtitlesOff")
                : named === option.key.toUpperCase() && track?.label ? track.label : named;
              return (
                <Option key={option.key} active={option.selected} onClick={() => onSubtitle(option.key === TRAILER_SUBTITLES_OFF ? null : option.key)}
                  label={label} detail={track?.auto ? t("common:trailerSubtitleAutoGenerated") : undefined} />
              );
            })}
          </Section>
        )}
        {qualityOptions.length > 0 && (
          <Section title={t("common:trailerQuality")}>
            {qualityOptions.map((option) => (
              <Option key={option.key} active={option.selected}
                onClick={() => onQuality(option.key === TRAILER_QUALITY_AUTO ? null : Number(option.key))}
                label={option.key === TRAILER_QUALITY_AUTO ? t("common:trailerQualityAuto") : t("common:trailerQualityHeight", { height: option.key })} />
            ))}
          </Section>
        )}
      </div>
    </motion.div>
  );
});

function Section({ title, children }: { title: string; children: ReactNode }) {
  return (
    <div className="mb-3 last:mb-0">
      <p className="mb-1.5 text-xs font-medium uppercase tracking-wider text-content-quaternary">{title}</p>
      <div className="space-y-0.5">{children}</div>
    </div>
  );
}

function Option({ label, detail, active, onClick }: { label: string; detail?: string; active: boolean; onClick: () => void }) {
  return (
    <button
      onClick={onClick}
      aria-pressed={active}
      className={`flex w-full items-center gap-2 rounded-lg px-3 py-2 text-left text-sm transition-colors ${
        active ? "bg-[rgba(var(--brand-rgb),0.25)] font-medium text-content-primary" : "text-content-tertiary hover:bg-fill-subtle hover:text-content-primary"
      }`}
    >
      <span className={`h-2 w-2 flex-shrink-0 rounded-full transition-colors ${active ? "bg-tentacle-accent" : "bg-fill-medium"}`} />
      <span className="flex min-w-0 flex-1 flex-col">
        <span className="truncate">{label}</span>
        {detail && <span className="truncate text-xs text-content-quaternary">{detail}</span>}
      </span>
    </button>
  );
}
